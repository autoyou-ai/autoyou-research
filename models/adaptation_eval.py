"""Independent summary of the multi-model, multi-task adaptation experiment.

The previous adaptation track used a literature-derived +2/+6/+14 point
scenario. This module provides the replacement data contract: observed paired
scores for the same tasks before and after adaptation, across several base
models and task classes. The primary estimand is absolute task-accuracy
change, not a ratio to a reference model. It intentionally returns
available=False until a real evaluation file is supplied. No synthetic scores
are generated by this evaluator.

Expected input:

    measure/results/adaptation-multimodel.json

The input is a public-safe aggregate file. It contains task identifiers and
scores, never prompts, answers, screenshots, or personal corpora.
"""

from __future__ import annotations

import argparse
import hashlib
import itertools
import json
import math
import random
import statistics
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = ROOT / "measure" / "results" / "adaptation-multimodel.json"
DEFAULT_OUTPUT = ROOT / "models" / "adaptation_evaluation.json"
TASK_CLASSES = (
    "extraction",
    "rag_qa",
    "summary",
    "simple_code",
    "hard_reason",
)
MIN_MODELS = 3
MIN_TASKS_PER_CLASS = 20


def _display_path(path: Path) -> str:
    """Keep generated reports portable instead of embedding a local path."""
    try:
        return path.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return str(path)


def _number(value: object) -> Optional[float]:
    try:
        out = float(value)
    except (TypeError, ValueError):
        return None
    return out if math.isfinite(out) else None


def _percentile(values: Sequence[float], probability: float) -> float:
    ordered = sorted(values)
    if len(ordered) == 1:
        return ordered[0]
    position = (len(ordered) - 1) * probability
    lo = math.floor(position)
    hi = math.ceil(position)
    if lo == hi:
        return ordered[lo]
    return ordered[lo] + (ordered[hi] - ordered[lo]) * (position - lo)


def _cluster_bootstrap(rows: Sequence[Dict[str, object]], value_key: str,
                       resamples: int, seed: int) -> Tuple[float, float]:
    """Bootstrap a mean while resampling model clusters, not raw rows."""
    by_model: Dict[str, List[float]] = {}
    for row in rows:
        value = _number(row.get(value_key))
        if value is not None:
            by_model.setdefault(str(row["model_id"]), []).append(value)
    clusters = [
        statistics.mean(values) for values in by_model.values() if values
    ]
    if not clusters:
        raise ValueError(f"no values for {value_key}")
    if len(clusters) == 1:
        return clusters[0], clusters[0]
    rng = random.Random(seed)
    draws = []
    for _ in range(resamples):
        sample = [clusters[rng.randrange(len(clusters))]
                  for _ in clusters]
        draws.append(statistics.mean(sample))
    return _percentile(draws, 0.025), _percentile(draws, 0.975)


def _cluster_permutation_pvalue(rows: Sequence[Dict[str, object]],
                                value_key: str, resamples: int,
                                seed: int) -> float:
    """Paired sign-flip test at the model-cluster level.

    Tasks within one model are not independent model replicates. The primary
    p-value therefore flips the sign of each model's mean delta. With a small
    number of models the exact sign space is enumerated, avoiding a falsely
    precise task-level p-value.
    """
    values_by_model: Dict[str, List[float]] = {}
    for row in rows:
        value = _number(row.get(value_key))
        if value is not None:
            values_by_model.setdefault(str(row["model_id"]), []).append(value)
    clusters = [statistics.mean(values) for values in values_by_model.values()
                if values]
    if not clusters:
        return 1.0
    observed = abs(statistics.mean(clusters))
    if len(clusters) <= 16:
        sign_vectors = itertools.product((-1.0, 1.0), repeat=len(clusters))
        extreme = sum(
            abs(statistics.mean(sign * value
                                for sign, value in zip(signs, clusters)))
            >= observed - 1e-15
            for signs in sign_vectors)
        return extreme / (2 ** len(clusters))
    rng = random.Random(seed)
    extreme = 0
    for _ in range(resamples):
        signed = [value if rng.randrange(2) else -value for value in clusters]
        if abs(statistics.mean(signed)) >= observed:
            extreme += 1
    return (extreme + 1) / (resamples + 1)


def _load(path: Path) -> Dict[str, object]:
    with path.open(encoding="utf-8") as handle:
        value = json.load(handle)
    if not isinstance(value, dict):
        raise ValueError(f"{path} is not a JSON object")
    return value


def _normalise_rows(data: Dict[str, object]) -> Tuple[List[Dict[str, object]], List[str]]:
    rows = []
    errors = []
    for model in data.get("models", []) or []:
        model_id = model.get("model_id")
        if not model_id:
            errors.append("model is missing model_id")
            continue
        for item in model.get("task_results", []) or []:
            task_id = item.get("task_id")
            task_class = item.get("task_class")
            if not task_id or task_class not in TASK_CLASSES:
                errors.append(f"{model_id}: invalid task id or task class")
                continue
            seed_scores = item.get("seed_scores")
            if seed_scores:
                if not isinstance(seed_scores, list):
                    errors.append(f"{model_id}/{task_id}: seed_scores must be a list")
                    continue
                per_seed = []
                for seed_row in seed_scores:
                    if not isinstance(seed_row, dict):
                        continue
                    values = {
                        "base": _number(seed_row.get("base_score")),
                        "adapted": _number(seed_row.get("adapted_score")),
                        "frontier": _number(seed_row.get("frontier_score")),
                    }
                    if all(value is not None and 0.0 <= value <= 1.0
                           for value in values.values()):
                        per_seed.append(values)
                if len(per_seed) != len(seed_scores):
                    errors.append(f"{model_id}/{task_id}: invalid seed score")
                    continue
                scores = {
                    key: statistics.mean(row[key] for row in per_seed)
                    for key in ("base", "adapted", "frontier")
                }
                seed_count = len(per_seed)
            else:
                scores = {
                    "base": _number(item.get("base_score")),
                    "adapted": _number(item.get("adapted_score")),
                    "frontier": _number(item.get("frontier_score")),
                }
                seed_count = 1
            if any(value is None or not 0.0 <= value <= 1.0
                   for value in scores.values()):
                errors.append(f"{model_id}/{task_id}: scores must be in [0, 1]")
                continue
            rows.append({
                "model_id": str(model_id),
                "adapter_id": str(model.get("adapter_id", "")),
                "device_id": str(model.get("device_id", "")),
                "task_id": str(task_id),
                "task_class": str(task_class),
                "seed_count": seed_count,
                "base_accuracy": scores["base"],
                "adapted_accuracy": scores["adapted"],
                "frontier_accuracy": scores["frontier"],
                "delta_accuracy": scores["adapted"] - scores["base"],
                "accuracy_uplift_pp": (scores["adapted"] - scores["base"]) * 100,
                # Compatibility aliases for callers that consume the raw pair.
                "base_score": scores["base"],
                "adapted_score": scores["adapted"],
                "frontier_score": scores["frontier"],
            })
    return rows, errors


def validate(data: Dict[str, object], rows: Sequence[Dict[str, object]],
             errors: Sequence[str]) -> Dict[str, object]:
    models = sorted({row["model_id"] for row in rows})
    tasks_by_class = {
        task_class: sorted({row["task_id"] for row in rows
                            if row["task_class"] == task_class})
        for task_class in TASK_CLASSES
    }
    duplicate_keys = {}
    for row in rows:
        key = (row["model_id"], row["task_id"])
        duplicate_keys[key] = duplicate_keys.get(key, 0) + 1
    duplicates = ["/".join(key) for key, count in duplicate_keys.items()
                  if count > 1]
    required_seeds = (data.get("protocol") or {}).get("seeds") or []
    seed_complete = (not required_seeds or
                     all(row["seed_count"] >= len(required_seeds)
                         for row in rows))
    checks = {
        "minimum_models": len(models) >= MIN_MODELS,
        "all_task_classes": all(tasks_by_class[task_class]
                                 for task_class in TASK_CLASSES),
        "minimum_tasks_per_class": all(
            len(tasks_by_class[task_class]) >= MIN_TASKS_PER_CLASS
            for task_class in TASK_CLASSES),
        "no_duplicate_model_task_pairs": not duplicates,
        "no_score_errors": not errors,
        "paired_scores": bool(rows),
        "seed_repetitions": seed_complete,
    }
    return {
        "passed": all(checks.values()),
        "checks": checks,
        "models": models,
        "model_count": len(models),
        "task_count_by_class": {
            key: len(value) for key, value in tasks_by_class.items()},
        "duplicate_model_task_pairs": duplicates,
        "input_errors": list(errors),
        "minimums": {
            "models": MIN_MODELS,
            "tasks_per_class": MIN_TASKS_PER_CLASS,
            "seeds": len(required_seeds) or 1,
        },
    }


def _summary(values: Sequence[float], resamples: int, seed: int
             ) -> Dict[str, object]:
    if not values:
        return {"n": 0}
    low, high = _bootstrap_values(values, resamples, seed)
    return {
        "n": len(values),
        "mean": statistics.mean(values),
        "median": statistics.median(values),
        "min": min(values),
        "max": max(values),
        "task_bootstrap_95_ci": {"low": low, "high": high,
                                 "resamples": resamples},
        "interpretation": (
            "Task-level repeatability interval within the supplied model "
            "records; it does not treat models as independent replicates."
        ),
    }


def _cluster_summary(rows: Sequence[Dict[str, object]], value_key: str,
                     resamples: int, seed: int) -> Dict[str, object]:
    """Summarize model-level means and bootstrap the model clusters."""
    values_by_model: Dict[str, List[float]] = {}
    for row in rows:
        value = _number(row.get(value_key))
        if value is not None:
            values_by_model.setdefault(str(row["model_id"]), []).append(value)
    cluster_values = [
        statistics.mean(values) for values in values_by_model.values()
        if values
    ]
    if not cluster_values:
        return {"n": 0, "model_clusters": 0}
    low, high = _cluster_bootstrap(rows, value_key, resamples, seed)
    return {
        "n": sum(len(values) for values in values_by_model.values()),
        "model_clusters": len(cluster_values),
        "model_mean": statistics.mean(cluster_values),
        "task_mean": statistics.mean(
            value for values in values_by_model.values() for value in values),
        "task_median": statistics.median(
            value for values in values_by_model.values() for value in values),
        "cluster_bootstrap_95_ci": {
            "low": low, "high": high, "resamples": resamples},
        "interpretation": (
            "The point estimate for inference is the mean of model-level "
            "task means; the bootstrap resamples model clusters rather than "
            "treating tasks from one model as independent devices."
        ),
    }


def _bootstrap_values(values: Sequence[float], resamples: int,
                      seed: int) -> Tuple[float, float]:
    if len(values) <= 1:
        return values[0], values[0]
    rng = random.Random(seed)
    draws = []
    for _ in range(resamples):
        draws.append(statistics.mean(
            values[rng.randrange(len(values))] for _ in values))
    return _percentile(draws, 0.025), _percentile(draws, 0.975)


def summarize_file(path: Path = DEFAULT_INPUT, resamples: int = 10000
                   ) -> Dict[str, object]:
    """Return measured adaptation uplift, or a structured no-data result."""
    if not path.exists():
        return {
            "available": False,
            "status": "NOT TESTED",
            "reason": (
                "multi-model, multi-task evaluation file is absent; the "
                "literature-derived uplift remains a scenario only"),
            "input": _display_path(path),
            "required_protocol": {
                "models": MIN_MODELS,
                "task_classes": list(TASK_CLASSES),
                "tasks_per_class": MIN_TASKS_PER_CLASS,
                "paired_base_adapted_frontier_scores": True,
            },
        }
    data = _load(path)
    raw = path.read_bytes()
    rows, errors = _normalise_rows(data)
    validation = validate(data, rows, errors)
    result = {
        "available": bool(validation["passed"]),
        "status": "MEASURED" if validation["passed"] else "INVALID DATA",
        "input": _display_path(path),
        "input_sha256": hashlib.sha256(raw).hexdigest(),
        "validation": validation,
        "protocol": data.get("protocol"),
        "models": [],
        "by_task_class": {},
    }
    if not validation["passed"]:
        result["reason"] = (
            "evaluation data do not meet the preregistered multi-model, "
            "multi-task requirements; no uplift is reported")
        return result

    for model_id in validation["models"]:
        model_rows = [row for row in rows if row["model_id"] == model_id]
        result["models"].append({
            "model_id": model_id,
            "adapter_id": model_rows[0]["adapter_id"],
            "device_id": model_rows[0]["device_id"],
            "task_count": len(model_rows),
            "uplift_pp": _summary(
                [row["accuracy_uplift_pp"] for row in model_rows],
                resamples, 500000 + len(result["models"])),
        })
    for index, task_class in enumerate(TASK_CLASSES):
        class_rows = [row for row in rows if row["task_class"] == task_class]
        result["by_task_class"][task_class] = {
            "task_count": len({row["task_id"] for row in class_rows}),
            "observation_count": len(class_rows),
            "base_accuracy": _cluster_summary(
                class_rows, "base_accuracy", resamples, 510000 + index),
            "adapted_accuracy": _cluster_summary(
                class_rows, "adapted_accuracy", resamples, 520000 + index),
            "frontier_accuracy": _cluster_summary(
                class_rows, "frontier_accuracy", resamples, 525000 + index),
            "uplift_pp": _cluster_summary(
                class_rows, "accuracy_uplift_pp", resamples, 530000 + index),
            "paired_cluster_permutation_p_two_sided": _cluster_permutation_pvalue(
                class_rows, "delta_accuracy", resamples, 560000 + index),
            "coverage_at_alpha_070": {
                "base": sum(row["base_accuracy"] >= 0.70 for row in class_rows)
                / len(class_rows),
                "adapted": sum(row["adapted_accuracy"] >= 0.70 for row in class_rows)
                / len(class_rows),
            },
        }
    class_p_values = {
        task_class: result["by_task_class"][task_class][
            "paired_cluster_permutation_p_two_sided"]
        for task_class in TASK_CLASSES
    }
    result["secondary_multiplicity"] = {
        "family": "five task-class uplift tests",
        "hypothesis_count": len(TASK_CLASSES),
        "correction": "Bonferroni",
        "alpha": 0.05,
        "raw_p_values": class_p_values,
        "adjusted_p_values": {
            task_class: min(1.0, value * len(TASK_CLASSES))
            for task_class, value in class_p_values.items()
        },
        "interpretation": (
            "Task-class tests are secondary and cluster-aware; the pooled "
            "adapted-minus-base result remains the only prespecified primary "
            "effect. Three model clusters make all class-level p-values coarse."
        ),
    }
    result["pooled"] = {
        "observation_count": len(rows),
        "model_count": validation["model_count"],
        "base_accuracy": _cluster_summary(
            rows, "base_accuracy", resamples, 535000),
        "adapted_accuracy": _cluster_summary(
            rows, "adapted_accuracy", resamples, 536000),
        "frontier_accuracy": _cluster_summary(
            rows, "frontier_accuracy", resamples, 537000),
        "uplift_pp": _cluster_summary(
            rows, "accuracy_uplift_pp", resamples, 540000),
        "paired_cluster_permutation_p_two_sided": _cluster_permutation_pvalue(
            rows, "delta_accuracy", resamples, 550000),
        # Kept as a stable, backwards-compatible field name. Its value is
        # now cluster-aware rather than the invalid task-level permutation.
        "paired_permutation_p_two_sided": _cluster_permutation_pvalue(
            rows, "delta_accuracy", resamples, 550000),
        "interpretation": (
            "The primary point estimate is the mean of model-level absolute "
            "adapted-minus-base task-accuracy changes, while the interval "
            "resamples model clusters to avoid treating tasks from one model "
            "as independent devices. The frontier is descriptive only. This "
            "is still an evaluation sample, not a universal workload mix."
        ),
    }
    result["replacement_rule"] = (
        "This measured result may replace the exploratory +2/+6/+14 uplift "
        "scenario only for the declared synthetic task-accuracy estimand. "
        "Do not use it as a real-workload or product quality headline; if the "
        "file is unavailable, report the scenario as unvalidated."
    )
    return result


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--resamples", type=int, default=10000)
    args = parser.parse_args(argv)
    if args.resamples < 100:
        parser.error("--resamples must be at least 100")
    result = summarize_file(args.input, args.resamples)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {args.output}")
    print(f"  status: {result['status']}")
    if result.get("available"):
        print(f"  models: {result['pooled']['model_count']}")
        print(f"  tasks: {result['pooled']['observation_count']}")
    else:
        print(f"  reason: {result.get('reason', 'requirements not met')}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
